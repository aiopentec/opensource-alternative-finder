#!/usr/bin/env python3
"""
apply_migrate_content_patch.py
Patches scripts/publish_github_pages.py so build_migration_page() renders
expanded long-form content (intro, elaborated steps, common challenges,
FAQ) whenever data/cache/migrate_content.json has an entry for that pair —
generated separately by scripts/migrate_content_generator.py.

Also fixes a separate bug found while investigating: migrate-*/index.html
pages currently ship with ZERO AdSense wiring — no google-adsense-account
meta tag, no adsbygoogle script, no ad unit. Every other page type on the
site has this; migrate pages were missed. This patch adds the same
verification meta tag, script snippet, and one in-content ad unit that
comparison pages already use (calling the existing get_adsense_snippet()
and get_adsense_unit() helpers — no new ad code, just wiring up what's
already there). Confirmed via `grep -c adsense` on build_migration_page()
returning 0 before this patch.

Pairs with no cached content yet keep rendering exactly as before (short
version), so this patch is safe to apply and commit before you've
generated any expanded content.

USAGE:
    Save this file in the ROOT of your opensource-alternative-finder repo
    (same folder as scripts/), then run:

        python3 apply_migrate_content_patch.py

    Then rebuild locally to confirm no errors:

        python3 scripts/publish_github_pages.py

Safe to re-run — checks for its own marker before patching and skips if
already applied.
"""
