def main():
    path = os.path.join(ROOT, TARGET)
    if not os.path.exists(path):
        print(f"ERROR: {TARGET} not found. Run this from the repo root.")
        sys.exit(1)

    with open(path) as f:
        src = f.read()

    if "MIGRATE_CONTENT_CACHE_PATH" in src:
        print(f"SKIP: {TARGET} already patched.")
        return

    for label, old, new in [
        ("imports + cache loader", IMPORT_OLD, IMPORT_NEW),
        ("expanded content builder", STEPS_HTML_OLD, STEPS_HTML_NEW),
        ("content div rendering", CONTENT_DIV_OLD, CONTENT_DIV_NEW),
        ("AdSense head tags (previously missing entirely)", HEAD_OLD, HEAD_NEW),
        ("AdSense in-content ad unit (previously missing entirely)", ADUNIT_OLD, ADUNIT_NEW),
    ]:
        if old not in src:
            print(f"ERROR: could not find the expected '{label}' block — your file may already "
                  f"differ from what this patch expects. No changes written.")
            sys.exit(1)
        if src.count(old) > 1:
            print(f"ERROR: the '{label}' block appears more than once — refusing to guess. No changes written.")
            sys.exit(1)
        src = src.replace(old, new)
        print(f"Patched: {label}")

    with open(path, "w") as f:
        f.write(src)

    print(f"\nDone. {TARGET} now renders expanded content when data/cache/migrate_content.json has it.")
    print("Next: run scripts/migrate_content_generator.py to populate that cache.")


if __name__ == "__main__":
    main()
